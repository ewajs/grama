/**
 * Builds the Spanish word lists the game ships, from pinned third-party sources (D12).
 * Run with `npm run words`. Downloads are cached in `.cache/` and checked against their
 * SHA-256, so the output is the same on every machine.
 */
import { decode } from '@msgpack/msgpack';
import { unzipSync } from 'fflate';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { expand, parseAffixes } from './hunspell.ts';
import { rankedWords } from './wordfreq.ts';
import { spanish } from '../src/core/spanish.ts';
import { preferSpelling, spelling, spellings } from './words.ts';

const SOURCES = {
  dictionary: {
    url: 'https://github.com/sbosio/rla-es/releases/download/v2.9/es_AR.oxt',
    sha256: 'e1793f41a686e86b9c59ede1d53046dcbdc43e449ae7640ea340c88dd0e78f5c',
  },
  frequency: {
    url: 'https://raw.githubusercontent.com/rspeer/wordfreq/v3.2/wordfreq/data/large_es.msgpack.gz',
    sha256: '14f326b4f68d517f9b8b99c1e26ef56a508d2dc8d0ee7a9e6e8732ddab1aa65e',
  },
};

/** How many of the most frequent words to ship; rarer ones add size, not targets. */
const FREQUENCY_WORDS = 30_000;

const CACHE = '.cache/sources';
const OUT = 'src/content/es';

const DICTIONARY_HEADER = `# Spanish (Argentina) words, one per line, uppercase with accents.
# Derived from the RLA-ES Spanish (Argentina) dictionary v2.9, (c) Santiago Bosio and the
# RLA-ES contributors, https://github.com/sbosio/rla-es. Licensed under the Mozilla Public
# License 2.0 (https://www.mozilla.org/MPL/2.0/). Modified: affixes expanded, filtered to
# 3-8 letters, uppercased. Generated by scripts/prepare-words.ts; see NOTICE.md.`;

const FREQUENCY_HEADER = `# Spanish words, most frequent first, uppercase with accents.
# Derived from wordfreq 3.2 by Robyn Speer, https://github.com/rspeer/wordfreq, which
# includes data from Google Books Ngrams, OpenSubtitles 2018 (opensubtitles.org),
# Wikipedia, ParaCrawl and the Leeds Internet Corpus. Modified: filtered, uppercased and
# ranked. Licensed under CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/).
# Generated by scripts/prepare-words.ts; see NOTICE.md.`;

async function download({ url, sha256 }: { url: string; sha256: string }): Promise<Buffer> {
  const path = `${CACHE}/${sha256}`;
  if (!existsSync(path)) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(path, Buffer.from(await response.arrayBuffer()));
  }
  const data = readFileSync(path);
  const actual = createHash('sha256').update(data).digest('hex');
  if (actual !== sha256) throw new Error(`${url}: expected SHA-256 ${sha256}, got ${actual}`);
  return data;
}

function write(file: string, header: string, words: string[]) {
  writeFileSync(`${OUT}/${file}`, `${header}\n${words.join('\n')}\n`);
  console.log(`${OUT}/${file}: ${words.length} words`);
}

const blocked = new Set(
  readFileSync('scripts/blocklist-es.txt', 'utf8')
    .split('\n')
    .filter((line) => line && !line.startsWith('#'))
    .map((word) => spanish.normalize(word)),
);

const oxt = unzipSync(new Uint8Array(await download(SOURCES.dictionary)));
const text = (name: string) => new TextDecoder().decode(oxt[name]);
const affixes = parseAffixes(text('es_AR.aff'));
// The first line of a .dic file is its entry count.
const entries = text('es_AR.dic').split('\n').slice(1);
const expanded = entries.flatMap((entry) => expand(entry, affixes));
const inDictionary = new Set(expanded.map(spelling));

// Frequency sources often drop accents ("tenes"): prefer spellings the dictionary knows.
const frequencyData = decode(gunzipSync(await download(SOURCES.frequency)));
const frequency = spellings(rankedWords(frequencyData), {
  blocked,
  prefer: preferSpelling((written) => inDictionary.has(written)),
}).slice(0, FREQUENCY_WORDS);

// Where the dictionary allows several spellings (ESTA, ESTÁ), agree with the frequency list.
const inFrequency = new Set(frequency);
const dictionary = spellings(expanded, {
  prefer: (candidate, current) =>
    inFrequency.has(candidate.written) && !inFrequency.has(current.written),
}).sort();

write('dictionary.txt', DICTIONARY_HEADER, dictionary);
write('frequency.txt', FREQUENCY_HEADER, frequency);
